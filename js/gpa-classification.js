// Given a school's raw avg_gpa_weighted (the single CDS-reported number) and
// its slug, returns { unweighted, weighted } -- exactly one is the reported
// value (placed per the classification above) and the other is null until
// filled in later from an outside source.
export function splitGpa(slug, rawGpa) {
  if (rawGpa == null) return { unweighted: null, weighted: null };
  const entry = GPA_CLASSIFICATION[slug];
  if (!entry || entry.classification === 'scale_anomaly') return { unweighted: null, weighted: null };
  return entry.classification === 'weighted'
    ? { unweighted: null, weighted: rawGpa }
    : { unweighted: rawGpa, weighted: null };
}
